"""v2.61 (Program 3, item 1): the split λ = 1 lift conditions of Q₀ → Q₁ are linear in μ, at every fold of Q₀.

Per vertex-block stratum of Q₀ (certificates logs/v2_58/certs_q0.jsonl: presolved coordinates vs, substitutions, the
stratum's equations rem): build P(μ) = P̄(vs) ⊕ P_J(λ = 1, μ) over ℚ[vs, m₀..m₆] (normal form (*) of v2.60), let Singular
generate its fold equations F and the conditions LIN (φ(B) ⊆ B), and split F by degree in μ (weights 0 on vs, 1 on μ).
With L = rem + LIN + (equations of μ-degree ≤ 1), enlarged by every remainder of μ-degree ≤ 1 left when an equation of
μ-degree ≥ 2 is reduced modulo L (each such remainder lies in the fold ideal), until stable; the claim is that then every
equation of μ-degree ≥ 2 lies in L, or failing that in √L (Rabinowitsch). Then for every fold P̄ in the stratum
(over any field of characteristic 0) the λ = 1 lifts are the solutions of a linear system in μ with coefficients
polynomial in P̄: M(P̄) is an affine subspace of B*, everywhere, not only generically.
Usage: python3 analysis/v2_61_mu_linear.py OUT_PREFIX [--only BLOCK] [--timeout S]"""
import os, sys, json, subprocess, collections, argparse
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.dirname(HERE)); sys.path.insert(0, HERE)
import numpy as np, sympy as sp
import fold_ideal as fi, pcensus as pc
ap = argparse.ArgumentParser(); ap.add_argument('out'); ap.add_argument('--only'); ap.add_argument('--timeout', type=int, default=3000)
A = ap.parse_args()
sys.argv = ['x', A.out]                                   # reuse the fold-equation generator of v2_61_mu_generic.py
__file__g = os.path.join(HERE, 'v2_61_mu_generic.py')
src = open(__file__g).read().split("out_rows = []")[0].replace("A = ap.parse_args()", "A_ = ap.parse_args()")
G_ = {'__file__': __file__g, '__name__': 'gen'}
exec(src, G_)
FOLD, groups, c1, b1, d1, idx1, e4 = (G_[k] for k in ('FOLD', 'groups', 'c1', 'b1', 'd1', 'idx1', 'e4'))
ss = lambda e: str(e).replace('**', '^')
tally = collections.Counter()
for block, g in groups.items():
    if A.only and block != A.only: continue
    st = g['stratum']; vs = st['vs']
    if not vs: print(f"{block}: a single point (nothing to check beyond the point itself)", flush=True); tally['point stratum'] += 1; continue
    V = [[-1 if ch == 'm' else int(ch) for ch in row] for row in block.split(',')]
    S = fi.stratum('pairs_in_short', V); R = S['R']; c0 = S['ctx']; b0 = c0['basis']; d0 = c0['d']
    DL0 = np.asarray(c0['DL'])
    gl = {str(x): x for x in R.gens}
    parse = lambda s_: R(sp.sympify(s_, locals={k: sp.Symbol(k) for k in gl}))
    Pr = [row[:] for row in S['P']]
    for x, v in st['subs']:
        xv, vv = gl[x], parse(v); Pr = [[e.compose(xv, vv) for e in row] for row in Pr]
    idx0 = {b: i for i, b in enumerate(b0)}
    B = [b for b in b0 if (b[0] == 'v' and b[1] == 1) or (b[0] == 'p' and c0['arrows'][b[1][-1]][1] == 1)]
    B0 = [idx0[b] for b in B]; Bpos = {i: k for k, i in enumerate(B0)}; nb = len(B)
    Bl = [idx1[('p', (5,))] if b[0] == 'v' else idx1[('p', b[1] + (5,))] for b in B]
    Qx = [idx1[b] for b in b0]
    mu = [f"m{k}" for k in range(nb)]
    # φ(p) = P̄p + Σ μ(suf) P̄(pre), as strings over ℚ[vs, μ]
    phi = [[f"({ss(Pr[r][B0[k]])})" for k in range(nb)] for r in range(d0)]
    for k, pi in enumerate(B0):
        for a, bb in zip(*np.nonzero(DL0[pi])):
            if bb in Bpos:
                for r in range(d0):
                    if Pr[r][a]: phi[r][k] += f"+({int(DL0[pi][a, bb])})*{mu[Bpos[bb]]}*({ss(Pr[r][a])})"
    lin = [phi[r][k] for r in range(d0) if r not in Bpos for k in range(nb)]
    Pm = [["0"] * d1 for _ in range(d1)]
    for i, qi in enumerate(Qx):
        for j, qj in enumerate(Qx): Pm[qi][qj] = f"({ss(Pr[i][j])})"
    Pm[e4][e4] = "1"
    for k in range(nb):
        for k2 in range(nb): Pm[Bl[k2]][Bl[k]] = phi[B0[k2]][k]
        Pm[e4][Bl[k]] = mu[k]
    nv = len(vs)
    w = ",".join(["0"] * nv + ["1"] * nb)
    src = [f'LIB "elim.lib"; ring r = 0,({",".join(vs + mu)},TT),dp; option(redSB);',
           f"ideal REM = {','.join(ss(e) for e in st['rem']) or '0'};",
           f"matrix PP[{d1}][{d1}] = " + ",".join(Pm[i][j] for i in range(d1) for j in range(d1)) + ";",
           FOLD, f"ideal LIN = {','.join(lin) or '0'};",
           f"intvec wt = {w},0; ideal FL; ideal FN; int ii;",
           "for (ii = 1; ii <= size(F); ii++) { if (deg(F[ii], wt) <= 1) { FL = FL + F[ii]; } else { FN = FN + F[ii]; } }",
           # saturate L by the μ-degree ≤ 1 remainders of the other equations (each is in I): if I = L at the end, I is
           # generated by elements of μ-degree ≤ 1, so every fibre's ideal is generated by affine-linear forms in μ
           "ideal SL = std(REM + LIN + FL); int changed = 1; int rounds = 0; poly rr;",
           "while (changed) { changed = 0; rounds++; for (ii = 1; ii <= size(FN); ii++) { rr = reduce(FN[ii], SL); "
           "if (rr != 0 && deg(rr, wt) <= 1) { SL = std(SL + rr); changed = 1; } } }",
           'print("ROUNDS " + string(rounds));',
           "int nred = 0; int nrad = 0; int nbad = 0;",
           "for (ii = 1; ii <= size(FN); ii++) { if (reduce(FN[ii], SL) == 0) { nred++; } else { "
           "ideal T = std(SL + ideal(1 - TT * FN[ii])); if (size(T) == 1 && deg(T[1]) == 0) { nrad++; } else { nbad++; } kill T; } }",
           'print("NONLIN " + string(size(FN)) + " INIDEAL " + string(nred) + " INRADICAL " + string(nrad) + " NOT " + string(nbad));',
           "quit;"]
    fn = f"{A.out}_{block.replace(',', '')}.sing"; open(fn, 'w').write("\n".join(src))
    try:
        rr = subprocess.run(["Singular", "-q", "--no-rc", fn], capture_output=True, text=True, timeout=A.timeout); res = rr.stdout + rr.stderr
    except subprocess.TimeoutExpired: res = 'TIMEOUT'
    if "NONLIN" not in res or "? " in res:
        print(f"{block}: unresolved ({res[-300:]})", flush=True); tally['unresolved'] += 1; continue
    w_ = res.split("NONLIN ")[1].split(); n, ir, rd, nt = int(w_[0]), int(w_[2]), int(w_[4]), int(w_[6])
    tally['linear' if nt == 0 else 'NOT linear'] += 1
    print(f"{block}: {n} fold equations of μ-degree ≥ 2: {ir} in L, {rd} in √L, {nt} neither -> "
          + ("the λ = 1 lift conditions are linear in μ at every point of the stratum" if nt == 0 else "NOT shown linear"), flush=True)
print("TALLY", dict(tally))
