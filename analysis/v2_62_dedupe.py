"""v2.62: merge the orbit representatives of v2_62_orbits.py into census classes, exactly over ℚ̄.

The census class of a fold P (v2.24) is generated by the census group G (column-sum-1 substitutions per parallel
class) and the class weightings w compatible at P (Σ_c w_c δ_c(P) = 0, a linear condition on the values w_c; the set
W(P) is a linear space, constant on G-orbits). Two representatives P, P' of one vertex block are tested for
P' = Φ(g) φ(t) P (Φ(g) φ(t))⁻¹ with g ∈ G, t ∈ W(P) ∩ 𝔾_m^classes, by a Gröbner basis over ℚ: unknowns are G's
parameters with an inverse of each class determinant and the weights with inverses; the pair is merged iff the ideal
is not the unit ideal (a solution over ℚ̄). Pairs are only tested when their invariants agree (orbit dimension under
𝔥_P = Der_Δ ⊕ E_{W(P)}, and dim W(P)). Classes are formed by union-find.
This merges along single census moves of the form g·t; the census also chains moves through intermediate folds, so the
result is an upper bound on the number of census classes over ℚ̄ (equal when no chaining is needed).
Writes OUT_PREFIX_classes.jsonl: one representative per class (P̄, W(P̄), orbit dimension).
Usage: python3 analysis/v2_62_dedupe.py ORBITS.jsonl OUT_PREFIX"""
import os, sys, json, subprocess, collections, itertools
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.dirname(HERE)); sys.path.insert(0, HERE)
import numpy as np, sympy as sp
import fold_ideal as fi, pcensus as pc
orbf, outp = sys.argv[1], sys.argv[2]
root = os.path.dirname(HERE)
reps = [json.loads(l) for l in open(orbf)]
certs = [json.loads(l) for l in open(os.path.join(root, 'logs', 'v2_58', 'certs_q0.jsonl'))]
strata = {r['block']: r for r in certs if r['kind'] == 'stratum'}
ctx = pc.setup('pairs_in_short', 3); d = ctx['d']; basis = ctx['basis']; arrows = ctx['arrows']
M = np.asarray(ctx['M']); DL = np.asarray(ctx['DL'])
idxb = {b: i for i, b in enumerate(basis)}
cls = collections.defaultdict(list)
for ai, st in enumerate(arrows): cls[st].append(ai)
cl = list(cls.values()); big = [c for c in cl if len(c) > 1]
# Φ(g) with generic parameters (v2_58_integral.py)
params = []; subs = {}; dets = []
for ci, c in enumerate(big):
    m = len(c); top = sp.Matrix(m - 1, m, lambda i, j: sp.Symbol(f'g{ci}_{i}{j}')); params += list(top)
    gm = top.col_join(sp.Matrix(1, m, lambda _, j: 1 - sum(top[:, j]))); dets.append(gm.det())
    for j, x in enumerate(c): subs[x] = {c[i]: gm[i, j] for i in range(m)}
Phi = sp.zeros(d, d)
for i, b in enumerate(basis):
    if b[0] == 'v': Phi[i, i] = 1; continue
    for choice in itertools.product(*[list(subs.get(x, {x: 1}).items()) for x in b[1]]):
        Phi[idxb[('p', tuple(x for x, _ in choice))], i] += sp.Mul(*[c_ for _, c_ in choice])
ws = sp.symbols(f'w0:{len(cl)}'); wa = {a: ws[k] for k, c in enumerate(cl) for a in c}
Ph = sp.diag(*[1 if b[0] == 'v' else sp.Mul(*[wa[x] for x in b[1]]) for b in basis])
U = (Phi * Ph).applyfunc(sp.expand)
DLc = []
for c in cl:
    D_ = np.zeros((d, d, d), dtype=np.int64)
    for l, b in enumerate(basis):
        if b[0] == 'v': continue
        for k, x in enumerate(b[1]):
            if x not in c: continue
            pre = idxb[('p', b[1][:k])] if k > 0 else idxb[('v', arrows[x][0])]
            suf = idxb[('p', b[1][k + 1:])] if k + 1 < len(b[1]) else idxb[('v', arrows[x][1])]
            D_[l, pre, suf] += 1
    DLc.append(D_)
def defects(P):        # δ_c(P) as flat vectors, exact
    out = []
    for D_ in DLc:
        lhs = np.einsum('ml,mab->lab', P, D_); rhs = np.einsum('ax,lxy,by->lab', P, D_, P)
        out.append(sp.Matrix((lhs - rhs).reshape(-1).tolist()))
    return out
def to_P(rec):
    V = [[-1 if ch == 'm' else int(ch) for ch in row] for row in rec['block'].split(',')]
    key = rec['block']
    if key not in SS:
        S = fi.stratum('pairs_in_short', V); R = S['R']; st = strata[key]
        gl = {str(x): x for x in R.gens}
        parse = lambda s_: R(sp.sympify(s_, locals={k: sp.Symbol(k) for k in gl}))
        Pr = [row[:] for row in S['P']]
        for x, v in st['subs']:
            xv, vv = gl[x], parse(v); Pr = [[e.compose(xv, vv) for e in row] for row in Pr]
        SS[key] = (sp.Matrix([[e.as_expr() for e in row] for row in Pr]), st)
    PrE, st = SS[key]
    pt = {sp.Symbol(k): sp.Rational(v) for k, v in rec['point'].items()}
    P = PrE.subs(pt)
    assert all(x.is_rational for x in P), "non-rational P"
    return P
SS = {}
DerD0 = None
from sympy.polys.matrices import DomainMatrix
def nullsp(rows, n):
    if not rows: return [sp.Matrix([1 if i == j else 0 for i in range(n)]) for j in range(n)]
    Nm = DomainMatrix.from_list_sympy(len(rows), n, rows).convert_to(sp.QQ).nullspace().to_Matrix()
    return [Nm.row(k).T for k in range(Nm.rows)]
Ec = [sp.diag(*[0 if b[0] == 'v' else sum(1 for x in b[1] if x in c) for b in basis]) for c in cl]
def info(P):
    Pi = np.array(P.tolist(), dtype=object)
    df = defects(Pi)
    W = nullsp([list(sp.Matrix.hstack(*df).row(i)) for i in range(len(df[0])) if any(sp.Matrix.hstack(*df).row(i))], len(cl))
    DerD = [sp.Matrix(d, d, [sp.Rational(x) for x in D]) for D in strata[next(iter(strata))]['DerD']]
    h = DerD + [sum((w[k] * Ec[k] for k in range(len(cl))), sp.zeros(d, d)) for w in W]
    rank = sp.Matrix([list(D * P - P * D) for D in h]).rank()
    return W, rank
by_block = collections.defaultdict(list)
for rec in reps: by_block[rec['block']].append(rec)
total = 0; lines = []
CLS = open(outp + '_classes.jsonl', 'w')
for block, recs in by_block.items():
    Ps = [to_P(r) for r in recs]; infs = [info(P) for P in Ps]
    par = list(range(len(Ps)))
    def find(x):
        while par[x] != x: par[x] = par[par[x]]; x = par[x]
        return x
    tests = 0
    for i, j in itertools.combinations(range(len(Ps)), 2):
        if find(i) == find(j): continue
        (Wi, ri), (Wj, rj) = infs[i], infs[j]
        if ri != rj or len(Wi) != len(Wj): continue
        tests += 1
        # t ∈ W(P_i): w = Σ a_k W_k (values), all w_c invertible
        a = sp.symbols(f'a0:{len(Wi)}'); wv = [sum(a[k] * Wi[k][c] for k in range(len(Wi))) for c in range(len(cl))]
        Ut = U.subs(dict(zip(ws, wv)))
        eqs = list((Ut * Ps[i] - Ps[j] * Ut).applyfunc(sp.expand))
        inv = sp.symbols(f'u0:{len(dets)}'); sv = sp.symbols(f's0:{len(cl)}')
        eqs += [sp.expand(inv[k] * dets[k] - 1) for k in range(len(dets))] + [sp.expand(sv[c] * wv[c] - 1) for c in range(len(cl))]
        eqs = [e for e in eqs if e != 0]
        allv = list(params) + list(a) + list(inv) + list(sv)
        src = [f"ring r = 0,({','.join(map(str, allv))}),dp;", f"ideal I = {','.join(str(e).replace('**', '^') for e in eqs)};",
               'ideal G = std(I); print("UNIT " + string(size(G) == 1 && deg(G[1]) == 0)); quit;']
        fn = f"{outp}_t.sing"; open(fn, 'w').write("\n".join(src))
        res = subprocess.run(["Singular", "-q", "--no-rc", fn], capture_output=True, text=True, timeout=600).stdout
        assert "UNIT" in res, res[-300:]
        if "UNIT 0" in res: par[find(i)] = find(j)
    ncls = len({find(i) for i in range(len(Ps))}); total += ncls
    for i in range(len(Ps)):
        if find(i) == i:                         # one representative per class, with its P̄ (rational entries)
            CLS.write(json.dumps(dict(block=block, rep=recs[i], P=[[str(x) for x in row] for row in Ps[i].tolist()],
                                      W=[[str(x) for x in w] for w in infs[i][0]], orbit_dim=infs[i][1],
                                      members=[k for k in range(len(Ps)) if find(k) == i])) + "\n"); CLS.flush()
    lines.append((block, len(Ps), ncls, tests))
    print(f"{block}: {len(Ps)} representatives → {ncls} classes ({tests} pair tests)", flush=True)
print(f"TOTAL {total}")
