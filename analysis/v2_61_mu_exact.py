"""v2.61 (Program 3, item 1), exact over ℚ: the split λ = 1 lifts of Q₀ → Q₁ over integral folds P̄ of Q₀.

Takes the G-orbit representatives of a census dump of Q₀ (entries lifted to {−(q−1)/2, …, (q−1)/2}), keeps those that are
folds of ℚQ₀ (exact integer check), and for each builds P(μ) = P̄ ⊕ P_J(λ = 1, μ) with μ = (m0, …, m6) symbolic
(normal form (*) of v2.60; the condition φ(B) ⊆ B gives linear equations). The full fold equations of P(μ) in ℚ[m] are
handed to Singular: reduced Gröbner basis, its maximal degree (1: the ideal is generated by affine-linear forms, so the
μ-fibre is an affine space, scheme-theoretically), the dimension, and whether 0 (the identity lift) is a solution.
Usage: python3 analysis/v2_61_mu_exact.py q OUT_PREFIX"""
import os, sys, pickle, subprocess, collections
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, os.path.dirname(HERE)); sys.path.insert(0, HERE)
import numpy as np
from sympy import QQ
from sympy.polys.rings import ring
import pcensus as pc
q, outp = int(sys.argv[1]), sys.argv[2]
class SafeU(pickle.Unpickler):
    OK = {('numpy._core.numeric', '_frombuffer'), ('numpy.core.numeric', '_frombuffer'), ('numpy', 'dtype'),
          ('numpy._core.multiarray', '_reconstruct'), ('numpy.core.multiarray', '_reconstruct'), ('numpy', 'ndarray')}
    def find_class(self, mod, name):
        if (mod, name) not in self.OK: raise pickle.UnpicklingError(f"refused global {mod}.{name}")
        return super().find_class(mod, name)
root = os.path.dirname(HERE)
R0 = SafeU(open(os.path.join(root, 'logs', f'reps_pairs_in_short_{q}.pkl'), 'rb')).load()
c1, c0 = pc.setup('pairs_in_short_tail', 3), pc.setup('pairs_in_short', 3)
b1, b0 = c1['basis'], c0['basis']; d1, d0 = len(b1), len(b0)
idx1 = {b: i for i, b in enumerate(b1)}; idx0 = {b: i for i, b in enumerate(b0)}
M0 = np.asarray(c0['M']); M1 = np.asarray(c1['M']); DL0 = np.asarray(c0['DL']); DL1 = np.asarray(c1['DL'])
e4 = idx1[('v', 3)]
B = [b for b in b0 if (b[0] == 'v' and b[1] == 1) or (b[0] == 'p' and c0['arrows'][b[1][-1]][1] == 1)]
B0 = [idx0[b] for b in B]; Bpos = {i: k for k, i in enumerate(B0)}; nb = len(B)
Bl = [idx1[('p', (5,))] if b[0] == 'v' else idx1[('p', b[1] + (5,))] for b in B]
Qx = [idx1[b] for b in b0]
def is_fold_Z(P, M, DL):                     # exact over ℤ (hence ℚ)
    d = P.shape[0]
    if (P @ P - P).any(): return False
    Q = np.eye(d, dtype=np.int64) - P
    for A, img in ((P, True), (Q, False)):
        prod = np.einsum('ia,jb,ijk->kab', A, A, M)
        Pu = np.einsum('lk,kab->lab', P, prod)
        if ((Pu - prod) if img else Pu).any(): return False
    return not (np.einsum('ml,mab->lab', P, DL) - np.einsum('ax,lxy,by->lab', P, DL, P)).any()
R, *ms = ring(','.join(f'm{k}' for k in range(nb)), QQ)
def fold_eqs(P):                             # P: d1×d1 list of ring elements → set of equations
    d = d1; eqs = set()
    PP = [[sum((P[i][k] * P[k][j] for k in range(d) if P[i][k] and P[k][j]), R(0)) for j in range(d)] for i in range(d)]
    for i in range(d):
        for j in range(d): eqs.add(PP[i][j] - P[i][j])
    nz = [(i, j, k, int(M1[i, j, k])) for i in range(d) for j in range(d) for k in range(d) if M1[i, j, k]]
    Qm = [[(R(1) if i == j else R(0)) - P[i][j] for j in range(d)] for i in range(d)]
    for A, img in ((P, True), (Qm, False)):
        for a in range(d):
            for b in range(d):
                u = [R(0)] * d
                for i, j, k, c in nz:
                    if A[i][a] and A[j][b]: u[k] += c * A[i][a] * A[j][b]
                Pu = [sum((P[l][k] * u[k] for k in range(d) if P[l][k] and u[k]), R(0)) for l in range(d)]
                for l in range(d): eqs.add(Pu[l] - u[l] if img else Pu[l])
    for l in range(d):
        PD = [[sum((P[a][x] * int(DL1[l][x, y]) for x in range(d) if DL1[l][x, y]), R(0)) for y in range(d)] for a in range(d)]
        for a in range(d):
            for b in range(d):
                lhs = sum((P[m][l] * int(DL1[m][a, b]) for m in range(d) if DL1[m][a, b]), R(0))
                eqs.add(lhs - sum((PD[a][y] * P[b][y] for y in range(d) if PD[a][y]), R(0)))
    eqs.discard(R(0)); return eqs
lab_seen = set(); results = []
for Pq, lab in zip(R0['greps'], R0['loc']):
    Pb = ((Pq.astype(np.int64) + q // 2) % q) - q // 2
    if not is_fold_Z(Pb, M0, DL0): continue
    # φ(p) = P̄p + Σ μ(suf) P̄(pre), in ring form (columns indexed by B)
    phi = [[R(int(Pb[r, B0[k]])) for k in range(nb)] for r in range(d0)]
    for k, pi in enumerate(B0):
        for a, bb in zip(*np.nonzero(DL0[pi])):
            if bb in Bpos:
                for r in range(d0):
                    if Pb[r, a]: phi[r][k] += int(DL0[pi][a, bb]) * int(Pb[r, a]) * ms[Bpos[bb]]
    lin = [phi[r][k] for r in range(d0) if r not in Bpos for k in range(nb) if phi[r][k]]      # φ(B) ⊆ B
    P = [[R(0)] * d1 for _ in range(d1)]
    for i, qi in enumerate(Qx):
        for j, qj in enumerate(Qx): P[qi][qj] = R(int(Pb[i, j]))
    P[e4][e4] = R(1)
    for k in range(nb):
        for k2 in range(nb): P[Bl[k2]][Bl[k]] = phi[B0[k2]][k]
        P[e4][Bl[k]] = ms[k]
    eqs = sorted(set(lin) | fold_eqs(P), key=str)
    src = [f"ring r = 0,({','.join(f'm{k}' for k in range(nb))}),dp; option(redSB);",
           f"ideal I = {','.join(str(e).replace('**', '^') for e in eqs) or '0'};", "ideal G = std(I); int i; int md = 0;",
           "for (i = 1; i <= size(G); i++) { if (deg(G[i]) > md) { md = deg(G[i]); } }",
           'print("DIM " + string(dim(G)) + " MAXDEG " + string(md) + " ZERO " + string(size(reduce(G, std(maxideal(1)))) == 0 && size(G) > 0 || (size(G) == 0)));',
           'print("G " + string(G)); quit;']
    fn = f"{outp}_{lab}_{len(results)}.sing"; open(fn, 'w').write("\n".join(src))
    out = subprocess.run(["Singular", "-q", "--no-rc", fn], capture_output=True, text=True, timeout=600).stdout
    m = out.split("DIM ")[1].split()
    dim_, md = int(m[0]), int(m[2])
    empty = dim_ == -1
    zero_ok = all(e.coeff(R(1)) == 0 if False else e(*([0] * nb)) == 0 for e in eqs)   # identity lift μ = 0
    results.append((lab, empty, dim_, md, zero_ok))
summ = collections.Counter((('empty' if e else f"affine dim {dm}" if md <= 1 else f"dim {dm}, degree {md}"), z) for _, e, dm, md, z in results)
print(f"q = {q} dump: {len(results)} G-orbit representatives are folds over ℚ; their λ = 1 μ-fibres:")
for k, v in sorted(summ.items(), key=lambda kv: str(kv[0])): print(f"  {k[0]}, identity lift (μ = 0) {'present' if k[1] else 'absent'}: {v}")
nonaff = [r for r in results if not r[1] and r[3] > 1]
print("non-affine fibres:", nonaff[:10])
