def grab(src, name):
    i = src.index(f"def {name}"); j = src.index(":=", i) + 2
    k = src.find("\n\n", j); body = src[j:k] if k > 0 else src[j:]
    return eval(body.split("/--")[0].replace("![", "[").strip())

s = sp.Symbol('s')
def coeffs(e):
    e = sp.expand(e)
    if e == 0: return []
    cs = sp.Poly(e, s).all_coeffs()[::-1]
    return [int(x) for x in cs]
def lean_mat(M, d):
    return "![" + ",\n    ".join("![" + ", ".join(str(coeffs(M[i, j])).replace(' ', '') for j in range(d)) + "]" for i in range(d)) + "]"

def inner(q, w):
    src = open(os.path.join(GEN, q + '.lean')).read()
    c = grab(src, 'c'); d = len(c)
    names = [x.split(': ')[1] for x in re.search(r"Basis \(index: path\): (.*)", src).group(1).split(', ')]
    mul = lambda x, y: [sp.expand(sum(c[i][j][m] * x[i] * y[j] for i in range(d) for j in range(d) if c[i][j][m])) for m in range(d)]
    one = [1 if n.startswith('e') else 0 for n in names]
    wv = [w.get(n, 0) for n in names]
    u = [one[i] + s * wv[i] for i in range(d)]
    uinv, pw = one[:], one[:]
    for _ in range(d): pw = mul(pw, [-s * x for x in wv]); uinv = [sp.expand(a + b) for a, b in zip(uinv, pw)]
    E = lambda j: [1 if i == j else 0 for i in range(d)]
    Phi = sp.Matrix([mul(mul(u, E(j)), uinv) for j in range(d)]).T
    Psi = sp.Matrix([mul(mul(uinv, E(j)), u) for j in range(d)]).T
    return d, Phi, Psi

