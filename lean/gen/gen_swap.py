# cross lemmas: Filt pair (Φ', Ψ') intertwining F_i(t) with mirror(F_j)(t')
Mtab = {mirror_name[j]: (Sm * F[j] * Sm.T).applyfunc(sp.expand) for j in range(4)}
allnames = {n: F[i] for i, n in enumerate(names)} | Mtab
