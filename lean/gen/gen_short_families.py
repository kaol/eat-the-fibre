"""Generate lean/EatTheFibre/Gen/two_pairs_short_fam{k}.lean (v2.49): the 18 inner-curve families of 1⇉2⇉3 + 1→3
(v2.42–v2.43: the curves meeting q orbits at q = 3, 5, 7 under the full Δ-compatible group). Each is
P_t = Inn(1 + t·x) P₀ Inn(1 + t·x)⁻¹ with P₀ an integer fold (symmetric lift of a merged 𝔽₅ representative) and
x = α δ_a + β δ_b + γ δ_aδ_b. Each file proves by reflection:
  `<f>_isFold`   : P_t is a fold over every commutative ring, for every t;
  `<f>_one_orbit`: Φ_t P₀ = P_t Φ_t with Φ_t = Inn(1 + t·x) a multiplicative bijection.
Usage: python3 lean/gen/gen_short_families.py CURVES_LOG REPS_5_merged.pkl [k ...]   (k: which families, default all)"""
import os, sys, pickle, re, ast
import numpy as np, sympy as sp
HERE = os.path.dirname(os.path.abspath(__file__))
logf, reps_file = sys.argv[1], sys.argv[2]; only = [int(x) for x in sys.argv[3:]]
sys.argv = ['x']
exec(open(os.path.join(HERE, 'gen.py')).read().split("\nif __name__")[0])
reps = pickle.load(open(reps_file, 'rb')); p = reps['p']
name = 'two_pairs_short'
basis, M, DL, nms = names_of(name); d = len(basis)
idx = {b: i for i, b in enumerate(basis)}
v = lambda *path: idx[('p', path)]
s = sp.Symbol('t')
dA = {v(0): 1, v(1): -1}; dB = {v(2): 1, v(3): -1}; dAB = {v(0, 2): 1, v(0, 3): -1, v(1, 2): -1, v(1, 3): 1}
def xdir(vec):
    a, b, c = vec; out = {}
    for coeff, dd in ((a, dA), (b, dB), (c, dAB)):
        for k_, w in dd.items(): out[k_] = out.get(k_, 0) + coeff * w
    return {k_: w for k_, w in out.items() if w}
one = [1 if b[0] == 'v' else 0 for b in basis]
def smul(a, b): return [sp.expand(sum(int(M[i, j, m]) * a[i] * b[j] for i in range(d) for j in range(d) if M[i, j, m])) for m in range(d)]
E = lambda j: [1 if i == j else 0 for i in range(d)]
def lean_mat(Mx):
    return "![" + ",\n    ".join("![" + ", ".join(str(coeffs(Mx[i, j], s)).replace(' ', '') for j in range(d)) + "]" for i in range(d)) + "]"
fams = [(int(m.group(2)), ast.literal_eval(m.group(3)), m.group(4)) for m in
        re.finditer(r"family: (\d+) local orbits, from rep (\d+) along (\([^)]*\)), signature classes \[([^\]]*)\]", open(logf).read())
        if int(m.group(1)) == p]
assert len(fams) == 18, len(fams)
written = []
for k, (i, vec, cls_) in enumerate(fams, 1):
    if only and k not in only: continue
    fname = f"fam{k}"
    Pz = ((reps['greps'][i].astype(np.int64) % p + p // 2) % p) - p // 2
    P0 = sp.Matrix(Pz.tolist())
    xd = xdir(vec)
    x = [s * xd.get(q, 0) for q in range(d)]
    u = [one[q] + x[q] for q in range(d)]; uinv = one[:]; pw = one[:]
    for _ in range(3): pw = smul(pw, [-y for y in x]); uinv = [sp.expand(a + b) for a, b in zip(uinv, pw)]
    Phi = sp.Matrix([smul(smul(u, E(j)), uinv) for j in range(d)]).T
    Psi = sp.Matrix([smul(smul(uinv, E(j)), u) for j in range(d)]).T
    Ps = (Phi * P0 * Psi).applyfunc(sp.expand)
    # fail fast: P_t is a fold over ℚ[t] (idempotent, im/ker subalgebras, Δ-compatible) before emitting Lean
    Qs = (sp.eye(d) - Ps).applyfunc(sp.expand)
    assert (Ps * Ps - Ps).applyfunc(sp.expand) == sp.zeros(d, d), (k, 'idem')
    for a_ in range(d):
        for b_ in range(d):
            pa, pb = smul(list(Ps[:, a_]), list(Ps[:, b_])), smul(list(Qs[:, a_]), list(Qs[:, b_]))
            assert (Ps * sp.Matrix(pa) - sp.Matrix(pa)).applyfunc(sp.expand) == sp.zeros(d, 1), (k, 'img')
            assert (Ps * sp.Matrix(pb)).applyfunc(sp.expand) == sp.zeros(d, 1), (k, 'ker')
    DLs = [sp.Matrix(DL[m_].tolist()) for m_ in range(d)]
    for l_ in range(d):
        assert (sum((Ps[m_, l_] * DLs[m_] for m_ in range(d)), sp.zeros(d, d)) - Ps * DLs[l_] * Ps.T).applyfunc(sp.expand) == sp.zeros(d, d), (k, 'delta')
    assert (Phi * Psi - sp.eye(d)).applyfunc(sp.expand) == sp.zeros(d, d), (k, 'inv')
    xs = " + ".join(f"{c}·{nm}" for c, nm in zip(vec, ("δa", "δb", "δaδb")) if c)
    doc = (f"family {k} of 1⇉2⇉3 + 1→3 (class {cls_}): P_t = Inn(1 + t·x) P₀ Inn(1 + t·x)⁻¹, x = {xs}; "
           f"from merged 𝔽_{p} representative {i}; meets q orbits at q = 3, 5, 7 (v2.42–v2.43)")
