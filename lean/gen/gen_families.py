def inner(xd, sign=1):
    x = [sign * s * xd.get(i, 0) for i in range(d)]
    u = [one[i] + x[i] for i in range(d)]; uinv = one[:]; pw = one[:]
    for _ in range(3): pw = smul(pw, [-y for y in x]); uinv = [sp.expand(a + b) for a, b in zip(uinv, pw)]
    return sp.Matrix([smul(smul(u, E(j)), uinv) for j in range(d)]).T
def lean_mat(Mx):
    return "![" + ",\n    ".join("![" + ", ".join(str(coeffs(Mx[i, j], s)).replace(' ', '') for j in range(d)) + "]" for i in range(d)) + "]"

