"""Generate lean/EatTheFibre/Gen/pairs_in_short_vblocks.lean (v2.52): for each of the 21 vertex blocks of
1⇉2⇇3 + 1→3, an integer fold realising it (from analysis/v2_52_realise.py) is a fold over every commutative ring, by
reflection (constant polynomials).
Usage: python3 lean/gen/gen_vblocks.py REALISE.json"""
import os, sys, json, ast
HERE = os.path.dirname(os.path.abspath(__file__))
js = json.load(open(sys.argv[1]))
sys.argv = ['x']
exec(open(os.path.join(HERE, 'gen.py')).read().split("\nif __name__")[0])
name = 'pairs_in_short'
basis, M, DL, nms = names_of(name); d = len(basis)
sys.path.insert(0, os.path.join(HERE, '..', '..'))
import numpy as np, pcensus as pc
ctx = pc.setup(name, 3)
assert ctx['basis'] == basis and (np.asarray(ctx['M']) == np.asarray(M)).all() and (np.asarray(ctx['DL']) == np.asarray(DL)).all(), \
    "gen.py and pcensus bases differ"
vid = [i for i, b in enumerate(basis) if b[0] == 'v']
L = [f'''/-
# The 21 vertex blocks of 1⇉2⇇3 + 1→3 are realised (v2.52)

For each vertex block V (V[i][j] = coefficient of e_i in P(e_j)), `vbkP` is an integer fold with that block. It is a
fold over every commutative ring (reflection). That these 21 are the only vertex blocks in characteristic 0 is a
Singular elimination over ℚ (`analysis/v2_52_vertex_ideal.py`), not part of this file.

Generated by lean/gen/gen_vblocks.py; do not edit by hand.
-/
import EatTheFibre.Gen.{name}

open Matrix EatTheFibre.Reflect

namespace EatTheFibre.Q_{name}
''']
for k, (Vs, P) in enumerate(sorted(js.items()), 1):
    V = ast.literal_eval(Vs)
    assert [[P[i][j] for j in vid] for i in vid] == [list(r) for r in V]
    rows = ",\n    ".join("![" + ", ".join(f"[{x}]" if x else "[]" for x in P[i]) + "]" for i in range(d))
    nm = f"vb{k}"
    L.append(f"/-- vertex block {V} -/\ndef {nm}P : Fin {d} → Fin {d} → Poly :=\n  ![{rows}]\n")
    L.append(f"theorem {nm}_idem : idemOK {nm}P = true := by decide +kernel")
    for part, fn in (("img", "imageOK c"), ("ker", "kernelOK c"), ("del", "deltaOK D")):
        for rr in range(d):
            L.append(f"theorem {nm}_{part}_{rr} : {fn} {nm}P {rr} = true := by decide +kernel")
    ex = lambda part: ", ".join(f"{nm}_{part}_{rr}" for rr in range(d))
    L.append(f"theorem {nm}_check : check c D {nm}P = true :=\n"
             f"  check_of_parts c D {nm}P {nm}_idem\n"
             f"    (fun i => by fin_cases i; exacts [{ex('img')}])\n"
             f"    (fun i => by fin_cases i; exacts [{ex('ker')}])\n"
             f"    (fun i => by fin_cases i; exacts [{ex('del')}])\n")
    L.append(f"theorem {nm}_isFold {{k : Type*}} [CommRing k] : (alg k).IsFold (evalM {nm}P 0) :=\n"
             f"  check_sound c D {nm}P 0 {nm}_check\n")
L.append(f"end EatTheFibre.Q_{name}\n")
out = os.path.join(HERE, '..', 'EatTheFibre', 'Gen', f'{name}_vblocks.lean')
open(out, 'w').write("\n".join(L)); print("wrote", out, len(js), "folds")
