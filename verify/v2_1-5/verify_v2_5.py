    for _ in range(L // e + 2): Pg.append(pmul(Pg[-1], coeffs(g)))
    C = lambda P, j, m: P[j][m - 1] if m - 1 < len(P[j]) else Fq(0)
    pf = {d * j + 1: j for j in range(L // d + 1)}; pg = {e * j + 1: j for j in range(L // e + 1)}
    reserved = {m - 1 - s: m for m in pf if m in pg and m > 1}
    if any(r in pf or r in pg for r in reserved): return None
    b = {}; first = True
    for m in range(1, L + 1):
        if m in pf:
            b[m] = -sum(C(Pf, pf[m], k) * b[k] for k in range(1, m)) / C(Pf, pf[m], m)
            if m in pg and sum(C(Pg, pg[m], k) * b[k] for k in range(1, m + 1)) != 0: return False
        elif m in pg: b[m] = -sum(C(Pg, pg[m], k) * b[k] for k in range(1, m)) / C(Pg, pg[m], m)
        elif m in reserved:
            M = reserved[m]; lf, lg = C(Pf, pf[M], M), C(Pg, pg[M], M)
