u, z = sp.symbols('u z')
def first_disagreement(f, g, K=12):
    d, e = sp.degree(f, u), sp.degree(g, u)
    pf = sp.series(sp.expand(f.subs(u, 1 / z) * z**d)**sp.Rational(1, d), z, 0, K).removeO()
    pg = sp.series(sp.expand(g.subs(u, 1 / z) * z**e)**sp.Rational(1, e), z, 0, K).removeO()
    diff = sp.expand(pg - pf)
